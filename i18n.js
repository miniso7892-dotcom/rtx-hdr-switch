  // 语言设置 → 实际语言：'auto' 时浏览器界面语言以 zh 开头用中文，否则英文
  function resolve(setting, uiLanguage) {
    if (setting === 'zh' || setting === 'en') return setting;
    return /^zh\b/i.test(String(uiLanguage == null ? '' : uiLanguage)) ? 'zh' : 'en';
  }

  // {name} 占位符；缺参数时保留原样
  function format(text, params) {
    if (!params) return text;
    return text.replace(/\{(\w+)\}/g, function (m, k) {
      return Object.prototype.hasOwnProperty.call(params, k) && params[k] != null ? String(params[k]) : m;
    });
  }

  function t(lang, key, params) {
    const d = DICT[lang] || DICT.zh;
    const text = Object.prototype.hasOwnProperty.call(d, key) ? d[key]
      : Object.prototype.hasOwnProperty.call(DICT.zh, key) ? DICT.zh[key] : key;
    return format(text, params);
  }

  const api = Object.freeze({ DICT: DICT, LANGS: LANGS, resolve: resolve, format: format, t: t });
